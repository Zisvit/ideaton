export type MatchResult =
  | { kind: 'topic'; topic: Topic }
  | { kind: 'miss' }

/** Keyword-матч: longest-substring, регистронезависимо; guard — раньше
 *  матчинга; при ничьей или нуле — честный miss («не угадываем»). */
export function matchTopic(query: string): MatchResult {
  const q = query.toLowerCase()
  for (const term of GUARD_TERMS) {
    if (q.includes(term)) return { kind: 'topic', topic: GUARD_TOPIC }
  }
  let best = 0
  let leader: Topic | null = null
  let tied = false
  for (const topic of TOPICS) {
    let score = 0
    for (const kw of topic.keywords) {
      if (q.includes(kw)) score = Math.max(score, kw.length)
    }
    if (score === 0) continue
    if (score > best) {
      best = score
      leader = topic
      tied = false
    } else if (score === best && best > 0) {
      tied = true
    }
  }
  if (best === 0 || !leader) return { kind: 'miss' }
  if (tied) return { kind: 'miss' } // не угадываем при ничьей (space-bunny)
  return { kind: 'topic', topic: leader }
}
